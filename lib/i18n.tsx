async function detectDeviceLanguage(): Promise<Language> {
  try {
    const stored = await AsyncStorage.getItem(LANGUAGE_KEY);
    if (stored === "en" || stored === "es") return stored;
  } catch {}

  try {
    if (Platform.OS === "web" && typeof navigator !== "undefined") {
      const navLangs = navigator.languages || [navigator.language];
      for (const lang of navLangs) {
        if (lang.startsWith("es")) return "es";
      }
    } else {
      const Localization = await import("@/lib/localization");
      const locales = Localization.getLocales();
      if (locales && locales.length > 0) {
        for (const locale of locales) {
          if (locale.languageCode === "es") return "es";
        }
      }
    }
  } catch {}

  return "en";
}

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguageState] = useState<Language>("en");
  const [ready, setReady] = useState(false);

  useEffect(() => {
    detectDeviceLanguage().then((lang) => {
      setLanguageState(lang);
      setReady(true);
    });
  }, []);

  useEffect(() => {
    currentLang = language;
  }, [language]);

  const setLanguage = useCallback(async (lang: Language, permanent = true) => {
    setLanguageState(lang);
    if (permanent) {
      try {
        await AsyncStorage.setItem(LANGUAGE_KEY, lang);
      } catch {}
    }
  }, []);

  const toggleLanguage = useCallback(() => {
    setLanguageState((prev) => {
      const next = prev === "en" ? "es" : "en";
      AsyncStorage.setItem(LANGUAGE_KEY, next).catch(() => {});
      return next;
    });
  }, []);

  const t = useCallback(
    (key: TranslationKey, params?: Record<string, string | number>): string => {
      const dict = translations[language];
      let value = (dict as any)[key] || (translations.en as any)[key] || key;
      if (params) {
        Object.entries(params).forEach(([k, v]) => {
          value = value.replace(`{${k}}`, String(v));
        });
      }
      return value;
    },
    [language]
  );

  if (!ready) return null;

  return (
    <LanguageContext.Provider value={{ language, setLanguage, toggleLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const ctx = useContext(LanguageContext);
  if (!ctx) throw new Error("useLanguage must be used within LanguageProvider");
  return ctx;
}
